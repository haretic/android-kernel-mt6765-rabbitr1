#!/usr/bin/env python3
"""Generate the "gadget" string overlays for the r1.

PRODUCT_CHARACTERISTICS is tablet (large-screen layouts and defaults), so aapt
picks every product="tablet" string: "About tablet", "Tablet is starting...".
The r1 is not a tablet. For each target this writes an overlay with those
strings, "tablet" replaced by "gadget" in the text.

The overlays are on /product at priority 1: the build puts the framework's and
CompanionDeviceManager's tablet strings in characteristics RROs on /product at
priority 0, and those outrank every /vendor overlay.

Usage: gen-gadget-overlays.py <android-source> <device-overlay-dir>
"""
from pathlib import Path
import re
import sys

# overlay name, target package, strings.xml relative to the Android source
TARGETS = [
    ('GadgetFrameworkResR1', 'android', 'frameworks/base/core/res/res/values/strings.xml'),
    ('GadgetSettingsR1', 'com.android.settings', 'packages/apps/Settings/res-product/values/strings.xml'),
    ('GadgetSystemUIR1', 'com.android.systemui',
     'frameworks/base/packages/SystemUI/res-product/values/strings.xml'),
    ('GadgetPackageInstallerR1', 'com.android.packageinstaller',
     'frameworks/base/packages/PackageInstaller/res/values/strings.xml'),
    ('GadgetStorageManagerR1', 'com.android.storagemanager',
     'packages/apps/StorageManager/res/values/strings.xml'),
    ('GadgetCompanionDeviceManagerR1', 'com.android.companiondevicemanager',
     'frameworks/base/packages/CompanionDeviceManager/res/values/strings.xml'),
    ('GadgetSetupWizardR1', 'org.lineageos.setupwizard',
     'packages/apps/SetupWizard/app/src/main/res/values/strings.xml'),
]
STRING = re.compile(r'<string\b([^>]*)\bproduct="tablet"([^>]*)>(.*?)</string>', re.S)
WORDS = [('TABLET', 'GADGET'), ('Tablet', 'Gadget'), ('tablet', 'gadget')]


def gadget(text):
    # Only the text: names and xliff ids keep their spelling.
    parts = re.split(r'(<[^>]*>)', text)
    for i in range(0, len(parts), 2):
        for old, new in WORDS:
            parts[i] = re.sub(rf'\b{old}(s?)\b', rf'{new}\1', parts[i])
    return ''.join(parts)


def overlay(source, out, name, package):
    entries = []
    for before, after, text in STRING.findall(source.read_text()):
        attrs = re.sub(r'\s+', ' ', (before + after)).strip()
        attrs = re.sub(r'\s*msgid="[^"]*"', '', attrs)
        entries.append(f'    <string {attrs}>{gadget(text)}</string>')
    if not entries:
        raise SystemExit(f'{source}: no product="tablet" strings')
    res = out/name/'res/values'
    res.mkdir(parents=True, exist_ok=True)
    (res/'gadget.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- SPDX-License-Identifier: Apache-2.0 -->\n'
        '<!-- Generated by rabbit-r1/scripts/gen-gadget-overlays.py: the product="tablet"\n'
        '     strings, with "tablet" replaced by "gadget". -->\n'
        '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2">\n'
        + '\n'.join(entries) + '\n</resources>\n')
    (out/name/'Android.bp').write_text(
        '// Generated by rabbit-r1/scripts/gen-gadget-overlays.py.\n'
        f'runtime_resource_overlay {{\n    name: "{name}",\n    product_specific: true,\n}}\n')
    short = name[len('Gadget'):-len('R1')].lower()
    (out/name/'AndroidManifest.xml').write_text(
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    package="com.rabbit.r1.overlay.gadget.{short}">\n'
        f'    <overlay android:targetPackage="{package}" android:isStatic="true" android:priority="1" />\n'
        '</manifest>\n')
    return len(entries)


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    for name, package, strings in TARGETS:
        print(f'{name}: {overlay(src/strings, out, name, package)} strings')


if __name__ == '__main__':
    main()
